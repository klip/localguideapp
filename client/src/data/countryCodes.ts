/**
 * Country calling codes for the profile page's phone field — a static
 * reference list, not DB-backed (there's no server-side use for it; the
 * split between "country code" and "local number" only exists in the UI,
 * see `ProfilePage.vue`). Every country and territory with an ITU calling
 * code, A–Z by English name; the name shown is `common.country.<iso2>` in
 * the viewer's language (CLDR). Countries sharing a code (+1, +7, +44…)
 * each have their own row; `primary` marks which one a stored number shows.
 */
export interface CountryCode {
  /** Country name, shown in the combobox suggestion list. */
  name: string
  /** E.164 dial code including the leading "+". */
  dialCode: string
  /** ISO 3166-1 alpha-2 — names the country (`common.country.<iso2>`). */
  iso2: string
  /**
   * The country a shared code reads as (+44 → United Kingdom, not Guernsey):
   * the phone is stored as one string, so on load only the code is known.
   */
  primary?: true
}

