/** The country a stored dial code shows as: its `primary` row when the code is shared. */
export function countryForDialCode(dialCode: string): CountryCode | undefined {
  return (
    COUNTRY_CODES.find((country) => country.dialCode === dialCode && country.primary) ??
    COUNTRY_CODES.find((country) => country.dialCode === dialCode)
  )
}
