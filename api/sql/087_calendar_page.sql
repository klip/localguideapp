  SELECT 'calendar' AS `route`, 'calendar.page' AS `prefix`, 'main' AS `area`, 0 AS `position`
  UNION ALL SELECT 'calendar', 'calendar.weekly', 'main', 1
  UNION ALL SELECT 'calendar', 'calendar.rules', 'main', 2
  UNION ALL SELECT 'calendar', 'calendar.exceptions', 'main', 3
