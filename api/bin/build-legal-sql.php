<?php

/**
 * Turns one version of a legal document's Markdown sources into a seed
 * migration for `legal_documents` (see api/sql/024_legal_documents.sql).
 *
 *   php api/bin/build-legal-sql.php terms 2026-10-15 > api/sql/025_terms_2026_10_15.sql
 *
 * Reads docs/legal/<slug>/<version>/<language>.md for every language in
 * `Translations::LANGUAGES`; each file's first line is `# Title`, the rest is
 * the body. Refuses to build if a language is missing, or if a translation's
 * `{{placeholders}}` differ from the English ones. The version is the date
 * the document takes effect (`published_at`, 00:00 UTC).
 */

require_once __DIR__.'/../classes/Translations.php';

[$script, $slug, $version] = $argv + [null, '', ''];
if (!preg_match('/^[a-z_]+$/', (string) $slug) || !preg_match('/^\d{4}-\d{2}-\d{2}$/', (string) $version)) {
    fwrite(STDERR, "Usage: php build-legal-sql.php <slug> <YYYY-MM-DD>\n");
    exit(1);
}

$dir = __DIR__."/../../docs/legal/{$slug}/{$version}";
$placeholders = static function (string $text): array {
    preg_match_all('/\{\{([a-z_]+)\}\}/', $text, $m);
    $keys = array_unique($m[1]);
    sort($keys);
    return $keys;
};
$quote = static function (string $value): string {
    return "'" . str_replace(['\\', "'"], ['\\\\', "''"], $value) . "'";
};

$rows = [];
$english = null;
foreach (Translations::LANGUAGES as $language) {
    $path = "{$dir}/{$language}.md";
    if (!is_file($path)) {
        fwrite(STDERR, "Missing {$path}\n");
        exit(1);
    }
    $text = str_replace("\r\n", "\n", (string) file_get_contents($path));
    [$first, $body] = explode("\n", $text, 2) + ['', ''];
    if (strpos($first, '# ') !== 0) {
        fwrite(STDERR, "{$path}: the first line must be '# Title'\n");
        exit(1);
    }
    $keys = $placeholders($text);
    $english = $english ?? $keys;
    if ($keys !== $english) {
        fwrite(STDERR, "{$path}: placeholders differ from English\n");
        exit(1);
    }
    $rows[] = sprintf(
        '(%s, %s, %s, %s, %s, %s, UTC_TIMESTAMP())',
        $quote($slug),
        $quote($version),
        $quote($language),
        $quote(trim(substr($first, 2))),
        $quote(trim($body)),
        $quote("{$version} 00:00:00")
    );
}

echo "-- Seed: `{$slug}` version {$version} in every language. Generated by\n";
echo "-- api/bin/build-legal-sql.php from docs/legal/{$slug}/{$version}/ — edit those\n";
echo "-- files and regenerate rather than editing this. Re-runnable, but it\n";
echo "-- upserts: re-running resets edits made in the database to the files' text.\n\n";
echo "SET NAMES utf8mb4;\n\n";
echo "INSERT INTO `legal_documents` (`slug`, `version`, `language`, `title`, `body`, `published_at`, `created_at`) VALUES\n";
echo implode(",\n", $rows), "\n";
echo "ON DUPLICATE KEY UPDATE `title` = VALUES(`title`), `body` = VALUES(`body`), `published_at` = VALUES(`published_at`);\n";
